const sha256 = z.string().regex(/^[a-f0-9]{64}$/);
const positiveInteger = z.number().int().positive().safe();
const pinSchema = z
  .object({ path: z.string().min(1).max(512), sha256, bytes: positiveInteger })
  .strict();
const policySchema = z
  .object({
    timeoutMs: positiveInteger.max(2147483647),
    maximumLogBytes: positiveInteger.max(16 * 1024 * 1024),
    maximumInputBytes: positiveInteger.max(64 * 1024 * 1024 * 1024),
    maximumOutputBytes: positiveInteger.max(16 * 1024 * 1024),
  })
  .strict();
const localInstallationSchema = z
  .object({
    kind: z.literal("CreatorCubeInstallation"),
    cube: z
      .object({
        kind: z.enum(["cube_local", "recorded_fixture"]),
        executable: z.string().min(1).max(4096),
        root: z.string().min(1).max(4096),
        codeFiles: z.array(pinSchema).min(1).max(4096),
        configuration: pinSchema,
        gptCheckpoint: pinSchema,
        shapeCheckpoint: pinSchema,
        license: z.string().min(1).max(2048),
      })
      .strict(),
    executablePin: z.object({ sha256, bytes: positiveInteger.max(512 * 1024 * 1024) }).strict(),
    policy: policySchema,
  })
  .strict();
const installationSchema = z.union([
  localInstallationSchema,
  z
    .object({
      kind: z.literal("CreatorCubeInstallation"),
      cube: remoteCubeConfigSchema,
      policy: policySchema,
    })
    .strict(),
]);

interface PreparedAssetJob {
  kind: "CreatorAssetPreparation";
  jobId: string;
  preparedAt: string;
  intent: CubeJobIntent;
  installation: CreatorCubeInstallation;
}
interface AssetJobOutcome {
  kind: "CreatorAssetOutcome";
  jobId: string;
  preparation: ArtifactReference;
  status: "locally_inspected" | "recovery_required";
  reason?: string;
  failureCode?: string;
  lock?: ArtifactReference;
  workerReceipt?: ArtifactReference;
  diagnostic?: ArtifactReference;
  executionOutcome?: ArtifactReference;
  sourceHash?: string;
  origin: "worker" | "explicit_output_reconciliation";
}
export interface CreatorAssetJobStatus {
  kind: "CreatorAssetJobStatus";
  jobId: string;
  assetId: string;
  storeDirectory: string;
  artifactDirectory: string;
  executionDirectory: string;
  status: "prepared" | "dispatched" | "recovery_required" | "locally_inspected" | "reviewed";
  preparation: ArtifactReference;
  dispatch?: ArtifactReference;
  outcome?: ArtifactReference;
  executionOutcome?: ArtifactReference;
  reconciliation?: ArtifactReference;
  review?: ArtifactReference;
  diagnostic?: ArtifactReference;
  workerReceipt?: ArtifactReference;
  lock?: AssetLock;
  lockArtifact?: ArtifactReference;
  reason?: string;
  failureCode?: string;
  mayRun: boolean;
  nativeReadiness: "unavailable";
  limitations: string[];
  composition?: ReviewedAssetCompositionResolution;
}
